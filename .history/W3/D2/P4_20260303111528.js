console.log("Switch Statements")
const day = "R";
switch (day) {
    case "":
        console.log("Start of the week");
        break;

    case "Wednesday":
        console.log("Mid of the week");
        break;

    case "Friday":
        console.log("End of the week");
        break;

    default:
        console.log("Some day in the week");
        break;

}